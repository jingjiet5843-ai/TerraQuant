  async fetch(request, env) {
    const url = new URL(request.url);
    if (url.hostname === 'www.shigong.app') { url.hostname = 'shigong.app'; return Response.redirect(url.toString(), 301); }
    if (url.pathname === '/api/chat') return chat(request, env);
    if (url.pathname === '/api/lead') return lead(request, env);
    if (url.pathname === '/api/report') return report(request, env);
    if (url.pathname === '/api/log') return logQA(request, env);
    return new Response(HTML, { headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'public, max-age=300' } });
  }
