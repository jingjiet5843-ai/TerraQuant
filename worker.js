// 开场是“门面”，之后每个问题都是付费的，全部用最好的 Opus。可在 Cloudflare 用 OPEN_MODEL / CHAT_MODEL 改。
const OPEN_MODEL = 'claude-opus-5-5';
const CHAT_MODEL = 'claude-opus-5-5';

const hits = new Map();               // 简单的限速：同一个网络地址 10 分钟最多 30 次
function limited(ip) {
  const now = Date.now();
  const list = (hits.get(ip) || []).filter(t => now - t < 600000);
  list.push(now);
  if (hits.size > 5000) hits.clear();
  hits.set(ip, list);
  return list.length > 30;
}
const json = (o, status) => new Response(JSON.stringify(o), { status, headers: { 'content-type': 'application/json' } });

async function chat(request, env) {
  if (request.method !== 'POST') return json({ error: 'method' }, 405);
  const origin = request.headers.get('origin') || '';
  if (!/^https:\/\/(www\.)?shigong\.app$/.test(origin) && !/\.workers\.dev$/.test(origin)) return json({ error: 'origin' }, 403);
  if (!env.ANTHROPIC_API_KEY) return json({ error: 'not_configured' }, 503);
  if (limited(request.headers.get('cf-connecting-ip') || 'unknown')) return json({ error: 'rate_limited' }, 429);

  let body;
  try { body = await request.json(); } catch (e) { return json({ error: 'bad_json' }, 400); }
  const tier = body.tier === 'paid' ? 'paid' : 'free';
  const facts = String(body.facts || '').slice(0, 6000);
  const msgs = (Array.isArray(body.messages) ? body.messages : [])
    .filter(m => m && (m.role === 'user' || m.role === 'assistant') && typeof m.content === 'string' && m.content.trim())
    .map(m => ({ role: m.role, content: m.content.slice(0, m.role === 'assistant' ? 3000 : 1500) }));
  const userTurns = msgs.filter(m => m.role === 'user').length;
  const alternates = msgs.every((m, i) => m.role === (i % 2 ? 'assistant' : 'user'));
  if (!msgs.length || !alternates || msgs[0].content !== OPENING || msgs[msgs.length - 1].role !== 'user' || userTurns > 9)
    return json({ error: 'bad_messages' }, 400);

  const system = RULES + '\n\n' + CHAT_STYLE + (tier === 'free' ? '\n\n' + FREE_HIDE : '') +
    '\n\n命盘资料（程序已精确排盘和推算，直接采用，不要自己重排）：\n' + facts;
  const up = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'x-api-key': env.ANTHROPIC_API_KEY, 'anthropic-version': '2023-06-01' },
    body: JSON.stringify({
      model: msgs.length === 1 ? (env.OPEN_MODEL || OPEN_MODEL) : (env.CHAT_MODEL || CHAT_MODEL),
      max_tokens: msgs.length === 1 ? 1800 : 900,
      // 规则和命盘每次都一样，存进缓存，之后几次读取只收约十分之一的钱
      system: [{ type: 'text', text: system, cache_control: { type: 'ephemeral' } }],
      messages: msgs, stream: true
    })
  });
  if (!up.ok) {
    console.log('anthropic error', up.status, (await up.text()).slice(0, 500));
    return json({ error: 'upstream', status: up.status }, 502);
  }
  return new Response(up.body, { headers: { 'content-type': 'text/event-stream; charset=utf-8', 'cache-control': 'no-store' } });
}

